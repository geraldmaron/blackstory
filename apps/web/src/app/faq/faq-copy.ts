/**
 * `/faq` copy.
 *
 * The questions are the ones a stranger actually asks in the first two minutes, in their own
 * words, including the two that are uncomfortable to answer: who is behind this, and how much of
 * it is machine-made. A marketing question ("What makes BlackStory different?") is not a question
 * anybody has ever typed, and none is here.
 *
 * VOICE. Same split as `/about`. An answer that states how the system behaves is impersonal; an
 * answer that is a person's choice, limit or invitation is first person, because one person runs
 * this and the honest answer to "will this last" is his to give. Nothing here says "we".
 *
 * EVERY ANSWER IS CHECKABLE. Nothing is described here that the repository does not already do:
 *   - grades and their definitions: `packages/domain/src/facts/confidence.ts` and
 *     `app/methodology/methodology-copy.ts` (`EVIDENCE_GRADE_DEFINITIONS`)
 *   - precision and dignity rules: `methodology-copy.ts` (`DIGNITY_RULES`)
 *   - coverage honesty: `methodology-copy.ts` (`LIMITATION_RULES`) and `components/story/story-copy.ts`
 *   - corrections, receipt code, one appeal: `app/corrections/CorrectionsSections.tsx`
 *   - leads reviewed before publication: the `/submit` registry entry and `about-copy.ts`
 *   - the writing pipeline: `docs/content/neo-voice.md` Part VIII,
 *     `docs/methodology/chapter-fact-validation.md`, the `blackstory-prose-review` and
 *     `blackstory-ringer-review` skills, and the gates in `packages/ops-data/scripts/articles.ts`
 *   - cover plates: `brand/cover-lock/v1/README.md` and
 *     `packages/domain/src/publication/cover-package.ts`
 *   - the citation command: `components/patterns/command-palette/command-registry.ts`
 * If an answer here ever outruns those files, the answer is wrong, not the files.
 *
 * NO MODEL NAMES, NO VERSIONS. Naming a vendor dates the page and tells a reader nothing they can
 * check. What matters is which decisions a machine is allowed to make, and that does not change
 * when the tooling does.
 */

