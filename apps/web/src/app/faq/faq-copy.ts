export type FaqEntry = {
  /** The question as a reader would type it. */
  readonly question: string;
  /** Consecutive paragraphs. Two is common, one is fine, four is a sign the answer is dodging. */
  readonly answer: readonly string[];
  /** Where to go next. Rendered as a quiet row under the answer, never as a call to action. */
  readonly links?: readonly FaqLink[];
};

export type FaqSection = {
  /** Anchor id, also used by the contents list at the top. */
  readonly id: string;
  readonly heading: string;
  readonly entries: readonly FaqEntry[];
};

